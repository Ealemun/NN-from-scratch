from nn import MLP


# =========================================================
# 1. Dataset XOR
# =========================================================

xs = [
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1],
]

ys = [
    0,
    1,
    1,
    0,
]


# =========================================================
# 2. Modèle
# =========================================================

model = MLP(
    2,
    [4, 1],
    activations=["tanh", "sigmoid"]
)


# =========================================================
# 3. Hyperparamètres
# =========================================================

epochs = 300
learning_rate = 0.1


# =========================================================
# 4. Boucle d'entraînement
# =========================================================

for epoch in range(epochs):

    # -----------------------------------------------------
    # Forward
    # -----------------------------------------------------

    ypred = [
        model(x)
        for x in xs
    ]

    # -----------------------------------------------------
    # Loss : somme des erreurs quadratiques
    # -----------------------------------------------------

    loss = sum(
        (yout - ygt) ** 2
        for yout, ygt in zip(ypred, ys)
    )

    # -----------------------------------------------------
    # Remise à zéro des gradients
    # -----------------------------------------------------

    model.zero_grad()

    # -----------------------------------------------------
    # Backpropagation
    # -----------------------------------------------------

    loss.backward()

    # -----------------------------------------------------
    # Mise à jour des paramètres
    # -----------------------------------------------------

    for p in model.parameters():
        p.data -= learning_rate * p.grad

    # -----------------------------------------------------
    # Affichage
    # -----------------------------------------------------

    if epoch % 20 == 0:
        print(
            f"epoch {epoch:3d} | "
            f"loss = {loss.data:.6f}"
        )


# =========================================================
# 5. Test final
# =========================================================

print("\nRésultats XOR :")

for x, y in zip(xs, ys):
    prediction = model(x)

    print(
        f"{x} -> "
        f"prediction={prediction.data:.4f} "
        f"(target={y})"
    )
